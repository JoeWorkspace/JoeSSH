function readOption(name) {
  const prefix = `${name}=`;
  const argument = process.argv
    .slice(2)
    .find((value) => value.startsWith(prefix));
  return argument ? argument.slice(prefix.length) : undefined;
}

function readGenerationSourceCommit() {
  try {
    return execFileSync("git", ["rev-parse", "HEAD"], {
      cwd: resolve(import.meta.dirname, ".."),
      encoding: "utf8",
    }).trim();
  } catch {
    return "working-tree-uncommitted";
  }
}

function readGenerationSourceState() {
  try {
    const status = execFileSync("git", ["status", "--porcelain"], {
      cwd: resolve(import.meta.dirname, ".."),
      encoding: "utf8",
    });
    return status.trim() ? "dirty-working-tree" : "clean-working-tree";
  } catch {
    return "working-tree-state-unknown";
  }
}

function readGenerationSourceStateOverride() {
  const override = readOption("--generation-source-state");
  if (override === undefined) return readGenerationSourceState();
  if (
    ![
      "clean-working-tree",
      "dirty-working-tree",
      "working-tree-state-unknown",
    ].includes(override)
  ) {
    throw new Error(
      `Invalid --generation-source-state=${override}; expected clean-working-tree, dirty-working-tree, or working-tree-state-unknown`,
    );
  }
  return override;
}

