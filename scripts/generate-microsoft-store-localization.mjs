function buildKeywords(features, locale) {
  const override = KEYWORD_OVERRIDES.get(locale) ?? {};
  return [
    "SSH",
    "SFTP",
    override.terminal ?? keywordFragment(features[1]),
    override.portForwarding ?? keywordFragment(features[3]),
    override.connectionProfiles ?? keywordFragment(features[4]),
    "Windows",
    "Public Beta",
  ].filter(
    (keyword, index, values) => keyword && values.indexOf(keyword) === index,
  );
}

